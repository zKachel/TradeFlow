/*
 * TradeFlow Service Worker – bewusst minimal.
 * - Seitenaufrufe: immer zuerst Netzwerk; nur wenn offline, die gespeicherte Offline-Seite zeigen.
 * - Es werden KEINE Seiten mit Nutzerdaten gecacht (wichtig ab Sprint 2 mit echten Daten).
 * - Statische Build-Dateien (/_next/static) werden zwischengespeichert, da sie unveränderlich sind.
 */
const VERSION = "v1";
const OFFLINE_CACHE = `tradeflow-offline-${VERSION}`;
const STATIC_CACHE = `tradeflow-static-${VERSION}`;
const OFFLINE_URL = "/offline";

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(OFFLINE_CACHE)
      .then((cache) => cache.addAll([OFFLINE_URL, "/icons/icon-192.png"]))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((k) => k.startsWith("tradeflow-") && k !== OFFLINE_CACHE && k !== STATIC_CACHE)
            .map((k) => caches.delete(k)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() => caches.match(OFFLINE_URL).then((r) => r || Response.error())),
    );
    return;
  }

  if (url.pathname.startsWith("/_next/static/")) {
    event.respondWith(
      caches.open(STATIC_CACHE).then((cache) =>
        cache.match(request).then(
          (hit) =>
            hit ||
            fetch(request).then((res) => {
              if (res.ok) cache.put(request, res.clone());
              return res;
            }),
        ),
      ),
    );
  }
});
